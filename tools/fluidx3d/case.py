"""Case generation for the FluidX3D Tier 2 runs: domain, units, rotation, case file, size budget.

Wind direction is handled by rotating the city into the lattice frame (wind along +x), see setup.cpp.template.
Frames: "city" = scenario coordinates (x east, y north, origin SW corner); "dom" = lattice frame, metres.
  p_dom  = R(-theta)(p_city - c_city) + c_dom        theta = Inflow.direction_deg (blowing toward, CCW from +x)
  p_city = c_city + R(theta)(p_dom - c_dom)
"""
from __future__ import annotations

import math
from dataclasses import dataclass
from pathlib import Path

from engine.scenario.schema import Inflow, Layout
from engine.wind.synthetic import log_law

DIRECTIONS_DEG = tuple(range(0, 360, 45))
GPU_FREE_MB = 4500          # RTX 3060 laptop: 6 GB, leave headroom
BYTES_PER_CELL_FP16S = 55   # D3Q19 + FP16S + flags etc. (from FluidX3D defines.hpp comments)


@dataclass
class Case:
    layout: Layout
    inflow: Inflow
    dx_m: float = 2.0
    ceiling_m: float = 128.0
    upstream_m: float = 100.0
    downstream_m: float = 200.0
    side_margin_m: float = 40.0
    n_snaps: int = 16
    snap_interval_s: float = 2.0
    settle_flowthroughs: float = 3.0
    peak_headroom: float = 1.25      # speed-up allowance above the log-law inflow
    lbm_u_cap: float = 0.07          # fastest expected lattice speed (guide: inflow <= 0.08)
    nu_floor: float = 0.0035         # tau = 0.5 + 3 nu = 0.5105 > 0.51

    @property
    def city_c(self):
        return (self.layout.area_m[0] / 2, self.layout.area_m[1] / 2)

    @property
    def radius(self) -> float:
        return 0.5 * math.hypot(*self.layout.area_m)

    @property
    def size_m(self):
        lx = self.upstream_m + 2 * self.radius + self.downstream_m
        ly = 2 * self.radius + 2 * self.side_margin_m
        return lx, ly, self.ceiling_m

    @property
    def shape(self):
        lx, ly, lz = self.size_m
        return (int(round(lx / self.dx_m / 4)) * 4, int(round(ly / self.dx_m / 4)) * 4, int(round(lz / self.dx_m)))

    @property
    def dom_c(self):
        return (self.upstream_m + self.radius, self.size_m[1] / 2)

    @property
    def lbm_u_ref(self) -> float:
        """Lattice speed of the 10 m reference wind so the fastest inflow cell (incl. headroom) <= lbm_u_cap."""
        top = float(log_law(self.ceiling_m, 1.0, self.inflow.roughness)) / float(log_law(10.0, 1.0, self.inflow.roughness))
        return self.lbm_u_cap / (top * self.peak_headroom)

    @property
    def dt_s(self) -> float:
        """Physical seconds per lattice step: dt = dx * u_lattice / u_si."""
        return self.dx_m * self.lbm_u_ref / self.inflow.speed_ms

    @property
    def snap_steps(self) -> int:
        return max(1, int(round(self.snap_interval_s / self.dt_s)))

    @property
    def settle_steps(self) -> int:
        flow_through_s = self.size_m[0] / self.inflow.speed_ms
        return int(round(self.settle_flowthroughs * flow_through_s / self.dt_s))

    def cells(self) -> int:
        nx, ny, nz = self.shape
        return nx * ny * nz

    def gpu_mb(self) -> float:
        return self.cells() * BYTES_PER_CELL_FP16S / 1e6

    def total_steps(self) -> int:
        return self.settle_steps + self.snap_steps * self.n_snaps

    def to_dom(self, p_city, theta_deg):
        t = math.radians(theta_deg)
        dx, dy = p_city[0] - self.city_c[0], p_city[1] - self.city_c[1]
        c, s = math.cos(-t), math.sin(-t)
        return (self.dom_c[0] + c * dx - s * dy, self.dom_c[1] + s * dx + c * dy)

    def to_city(self, p_dom, theta_deg):
        t = math.radians(theta_deg)
        dx, dy = p_dom[0] - self.dom_c[0], p_dom[1] - self.dom_c[1]
        c, s = math.cos(t), math.sin(t)
        return (self.city_c[0] + c * dx - s * dy, self.city_c[1] + s * dx + c * dy)

    def check(self) -> None:
        if self.gpu_mb() > GPU_FREE_MB:
            raise ValueError(f"domain {self.shape} needs ~{self.gpu_mb():.0f} MB VRAM > {GPU_FREE_MB} MB; raise dx_m")
        if self.lbm_u_ref * 1.0 > 0.08:
            raise ValueError("lattice inflow speed above 0.08")
        if 0.5 + 3 * self.nu_floor <= 0.51:
            raise ValueError("tau must stay > 0.51")

    def case_text(self, theta_deg: float, export_dir: str | Path) -> str:
        """Text of aeroswarm_case.txt read by setup.cpp.template."""
        self.check()
        t = math.radians(theta_deg)
        nx, ny, nz = self.shape
        lines = [
            "# generated by tools/fluidx3d/case.py - do not edit",
            f"nx {nx}", f"ny {ny}", f"nz {nz}", f"dx_m {self.dx_m}",
            f"u_ref_si {self.inflow.speed_ms}", f"z0 {self.inflow.roughness}", f"lbm_u_ref {self.lbm_u_ref:.6f}",
            f"nu_floor {self.nu_floor}", f"cos_t {math.cos(t):.9f}", f"sin_t {math.sin(t):.9f}",
            f"dom_cx {self.dom_c[0]}", f"dom_cy {self.dom_c[1]}", f"city_cx {self.city_c[0]}", f"city_cy {self.city_c[1]}",
            f"settle_steps {self.settle_steps}", f"snap_steps {self.snap_steps}", f"n_snaps {self.n_snaps}",
            f"export_dir {str(export_dir).replace(chr(92), '/').rstrip('/')}/",   # forward slashes work on Windows too
        ]
        lines += [f"building {b.x} {b.y} {b.w} {b.d} {b.h}" for b in self.layout.buildings]
        return "\n".join(lines) + "\n"


def field_bytes(layout: Layout, dx_m: float = 2.0, zmax_m: float = 80.0, n_frames: int = 16) -> int:
    """float16 [nx, ny, nz, 3] per frame, as stored by convert.py."""
    nx, ny = (int(round(v / dx_m)) for v in layout.area_m)
    nz = int(round(zmax_m / dx_m))
    return nx * ny * nz * 3 * 2 * n_frames
